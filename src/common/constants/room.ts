/**
 * 방 실시간(대기 로비) 정책.
 */
export const ROOM = {
  /**
   * 대기(waiting) 중 소켓이 끊겼을 때, 참가자 슬롯을 곧바로 비우지 않고 이만큼 기다린다.
   * 로컬 개발의 서버 재시작(nest --watch)·socket.io ping timeout·탭 백그라운드처럼
   * 잠깐 끊겼다 곧 재접속하는 경우에 대기 중이던 참가자가 튕겨 나가지 않게 하는 유예다.
   * 이 시간 안에 같은 닉네임이 재접속(재-join)하면 제거를 취소한다. 게임 중/종료 상태는
   * 원래부터 슬롯을 유지하므로(reclaim) 이 유예는 대기 상태에만 적용된다.
   *
   * 모바일에서 화면을 끄거나 다른 앱으로 전환하면 백그라운드 탭이 멈춰 소켓 핑이 끊긴다.
   * 대기 로비에서 폰을 잠깐 내려놓은 참가자까지 튕겨 나가지 않도록 유예를 넉넉히 둔다 —
   * 이 값이 크면 진짜 나간 사람이 그만큼 오래 목록에 남는 단점만 커진다(방 수명 자체는 별개로 3일).
   */
  WAITING_LEAVE_GRACE_MS: 5 * 60 * 1000, // 5분
} as const;
