/**
 * 방 실시간(대기 로비) 정책.
 */
export const ROOM = {
  /**
   * 대기(waiting) 중 소켓이 끊겼을 때, 참가자 슬롯을 곧바로 비우지 않고 이만큼 기다린다.
   * socket.io ping timeout·짧은 네트워크 끊김·새로고침처럼 잠깐 끊겼다 곧 재접속하는 경우에
   * 대기 중이던 참가자가 튕겨 나가지 않게 하는 유예다. 이 시간 안에 같은 닉네임이 재접속(재-join)하면
   * 제거를 취소한다. 게임 중/종료 상태는 별도로 처리한다(참가자 튕김 시 게임 중단 → 로비 복귀).
   *
   * 예전엔 5분으로 넉넉했으나, 참가자가 창을 닫고 나가도 5분간 '나감' 표시가 안 떠 다른 사람이
   * 오래 헷갈렸다. 그래서 짧게(30초) 줄인다 — 창을 닫으면 30초 뒤 '나갔어요'가 뜬다. 백그라운드로
   * 잠깐 내려놓은 모바일 참가자는 포그라운드 복귀 시 클라이언트가 자동 재접속(재-join)해 다시 들어온다.
   */
  WAITING_LEAVE_GRACE_MS: 30 * 1000, // 30초

  /**
   * 호스트(방장) 소켓이 끊겼을 때, 이만큼 기다렸다 재접속이 없으면 방을 닫는다(전원 홈으로 + '방 삭제' 안내).
   * 호스트가 새로고침·잠깐의 네트워크 끊김으로 튕겼다 곧 돌아오는 경우엔 방을 닫지 않도록 유예를 둔다.
   * 이 시간 안에 host 가 재접속(hostToken 으로 재연결)하면 닫기를 취소한다. 참가자 유예(5분)보다
   * 짧게 둔다 — 호스트가 진짜 나갔는데도 참가자가 오래 방에 갇혀 있지 않게 하려는 것이므로.
   */
  HOST_GONE_GRACE_MS: 30 * 1000, // 30초

  /**
   * 게임 진행 중 참가자 소켓이 끊겼을 때, 이만큼 기다렸다 재접속이 없으면 그 참가자를 내보내고
   * 게임을 중단해 전원(남은 참가자·호스트)을 로비로 되돌린다. 새로고침·짧은 끊김으로 곧 돌아오면
   * (재접속) 게임을 유지한다. 게임 중 이탈은 판을 이어갈 수 없으니 유예를 짧게 둔다.
   */
  PLAYER_DROP_GRACE_MS: 10 * 1000, // 10초
} as const;
