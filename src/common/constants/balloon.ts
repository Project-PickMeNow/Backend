/**
 * 풍선 터뜨리기(러시안 룰렛식) 정책.
 * 호스트를 포함한 참가자들이 순서대로 자기 턴에 가운데 풍선을 펌프(공기 주입)한다.
 * 한 턴에 최대 MAX_PER_TURN 번까지 펌프할 수 있고(1번 이상 펌프하면 '넘기기'로 다음 사람에게 넘긴다),
 * 게임을 시작하면 서버가 총 펌프 수(=풍선 크기)를 '인원수 × MAX_PER_TURN × ROUNDS' 로 자동 계산하고,
 * 그 안에서 1..크기 사이의 비밀 '터지는 순번'을 정한다.
 * 누적 펌프 수가 그 순번에 도달하는 순간 풍선이 펑 터지고, 그때 펌프한 사람이 '걸림'(패배)이 되며 끝난다.
 *
 * 각 턴에는 TURN_MS(60초) 제한 시간이 있다. 시간이 다 되면(호스트 클라이언트가 감지해 balloon:timeout 호출):
 *   - 이번 턴에 한 번도 안 펌프했으면 → 자동으로 1번 펌프하고 다음 사람에게 넘긴다(터지면 그 사람이 걸림).
 *   - 이미 1번 이상 펌프했으면 → 그냥 다음 사람에게 넘긴다.
 */
export const BALLOON = {
  /** 게임이 성립하려면 필요한 최소 턴 참가자 수(호스트 포함). 호스트도 참가하므로 참가자 1명이면 성립. */
  MIN_PLAYERS: 2,
  /** 한 턴에 펌프할 수 있는 최대 횟수 */
  MAX_PER_TURN: 3,
  /**
   * 총 펌프 수(=풍선 크기) 계산용 라운드 수.
   * 총 펌프 = 인원수(호스트 포함) × MAX_PER_TURN × ROUNDS (= 인원수 × 3 × 3).
   * 대략 모두가 ROUNDS 바퀴씩 최대치로 펌프해야 반드시 터지는 크기라, 인원이 많을수록 오래 간다.
   */
  ROUNDS: 3,
  /** 한 턴 제한 시간(ms). 이 시간이 지나면 자동 펌프(미펌프 시) 후 다음 사람으로 넘어간다. */
  TURN_MS: 60_000,
  /** 턴 순서에서 호스트를 나타내는 이름(참가자 닉네임과 구분). */
  HOST_NAME: '호스트',
} as const;
